import { readFile, mkdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const tokenDir = path.join(root, "design", "system", "tokens");
const outputDir = path.join(root, "src", "renderer", "design-system", "generated");

const readJson = async (name) =>
  JSON.parse(await readFile(path.join(tokenDir, name), "utf8"));

const [referenceDocument, semanticDocument, componentDocument] = await Promise.all([
  readJson("reference.tokens.json"),
  readJson("semantic.tokens.json"),
  readJson("component.tokens.json")
]);

delete referenceDocument.$schema;
delete referenceDocument.meta;
delete semanticDocument.$schema;
delete componentDocument.$schema;

const scopes = {
  ref: referenceDocument,
  semantic: semanticDocument,
  component: componentDocument
};

function valueAtAlias(alias) {
  const [scope, ...segments] = alias.split(".");
  let value = scopes[scope];
  for (const segment of segments) value = value?.[segment];
  return value;
}

function isLeaf(value) {
  if (value === null || Array.isArray(value) || typeof value !== "object") return true;
  const keys = Object.keys(value);
  return keys.includes("light") || keys.includes("dark");
}

function flatten(value, prefix = [], entries = []) {
  for (const [key, child] of Object.entries(value)) {
    const next = [...prefix, key];
    if (isLeaf(child)) entries.push([next, child]);
    else flatten(child, next, entries);
  }
  return entries;
}

function kebab(value) {
  return value
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .replace(/[^a-zA-Z0-9]+/g, "-")
    .replace(/^-|-$/g, "")
    .toLowerCase();
}

function variableName(scope, tokenPath) {
  const prefix = scope === "semantic" ? "tr" : `tr-${scope}`;
  return `--${prefix}-${tokenPath.map(kebab).join("-")}`;
}

function aliasToVariable(value) {
  if (typeof value !== "string") return String(value);
  const alias = value.match(/^\{(ref|semantic|component)\.(.+)\}$/);
  if (!alias) return value;
  return `var(${variableName(alias[1], alias[2].split("."))})`;
}

function validateTokens() {
  const errors = [];
  const variableOwners = new Map();
  const aliases = new Map();
  for (const [scope, document] of Object.entries(scopes)) {
    for (const [tokenPath, raw] of flatten(document)) {
      const owner = `${scope}.${tokenPath.join(".")}`;
      const variable = variableName(scope, tokenPath);
      const existing = variableOwners.get(variable);
      if (existing) errors.push(`Variable name collision: ${existing} and ${owner} -> ${variable}`);
      variableOwners.set(variable, owner);

      if (scope === "semantic" && typeof raw === "object") {
        if (!("light" in raw) || !("dark" in raw)) errors.push(`Theme token is incomplete: ${owner}`);
      }

      const values = typeof raw === "object" ? Object.values(raw) : [raw];
      for (const value of values) {
        if ((typeof value !== "string" && typeof value !== "number") || value === "") {
          errors.push(`Token value must be a non-empty string or number: ${owner}`);
          continue;
        }
        if (typeof value !== "string") continue;
        const alias = value.match(/^\{(.+)\}$/)?.[1];
        if (alias) {
          if (valueAtAlias(alias) === undefined) errors.push(`Unknown alias: ${owner} -> ${alias}`);
          else aliases.set(owner, [...(aliases.get(owner) ?? []), alias]);
        }
      }
    }
  }

  const visiting = new Set();
  const visited = new Set();
  function visit(owner, chain = []) {
    if (visiting.has(owner)) {
      errors.push(`Alias cycle: ${[...chain, owner].join(" -> ")}`);
      return;
    }
    if (visited.has(owner)) return;
    visiting.add(owner);
    for (const target of aliases.get(owner) ?? []) {
      if (aliases.has(target)) visit(target, [...chain, owner]);
    }
    visiting.delete(owner);
    visited.add(owner);
  }
  for (const owner of aliases.keys()) visit(owner);

  if (errors.length) throw new Error(`Invalid design tokens:\n${errors.join("\n")}`);
}

validateTokens();

function declarations(entries, scope, mode) {
  return entries
    .map(([tokenPath, raw]) => {
      const value = isLeaf(raw) && typeof raw === "object" ? raw[mode] ?? raw.light : raw;
      return `  ${variableName(scope, tokenPath)}: ${aliasToVariable(value)};`;
    })
    .join("\n");
}

const referenceEntries = flatten(scopes.ref);
const semanticEntries = flatten(scopes.semantic);
const componentEntries = flatten(scopes.component);

const css = `/* Generated by scripts/build-design-tokens.mjs. Do not edit. */
:root {
${declarations(referenceEntries, "ref", "light")}
${declarations(componentEntries, "component", "light")}
}

:root,
:root[data-theme="light"] {
  color-scheme: light;
${declarations(semanticEntries, "semantic", "light")}
}

:root[data-theme="dark"] {
  color-scheme: dark;
${declarations(semanticEntries, "semantic", "dark")}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme]) {
    color-scheme: dark;
${declarations(semanticEntries, "semantic", "dark")}
  }
}
`;

const maps = {};
for (const [scope, document] of Object.entries(scopes)) {
  maps[scope] = Object.fromEntries(
    flatten(document).map(([tokenPath]) => [tokenPath.join("."), `var(${variableName(scope, tokenPath)})`])
  );
}
const ts = `/* Generated by scripts/build-design-tokens.mjs. Do not edit. */\nexport const tokens = ${JSON.stringify(maps, null, 2)} as const;\n`;

await mkdir(outputDir, { recursive: true });
await Promise.all([
  writeFile(path.join(outputDir, "tokens.css"), css, "utf8"),
  writeFile(path.join(outputDir, "tokens.ts"), ts, "utf8")
]);

console.log(`Generated ${referenceEntries.length + semanticEntries.length + componentEntries.length} design tokens.`);
